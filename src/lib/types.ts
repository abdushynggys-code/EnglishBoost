import type { Preferences } from './preferences';
import type { ConciseAttempt } from './summaryTypes';
export type Skill = 'Grammar' | 'Vocabulary' | 'Reading' | 'Writing' | 'Speaking';
export type Profile = {
  id: string;
  email: string;
  full_name: string;
  role: 'student' | 'tutor';
  approved: boolean;
  goal: string;
  weekly_target: number;
  language?: Preferences['language'] | null;
  learning_track?: Preferences['learning_track'];
  learning_level?: Preferences['learning_level'];
  sound_effects?: boolean;
};
export type Lesson = {
  id: string;
  week: number;
  title: string;
  description: string;
  objectives: string[];
  activities: string;
  homework: string;
  duration: number;
  skill: Skill;
  practice_path?: string;
  book_unit?: string;
  book_page?: string;
  activities_de?: string;
  activities_ru?: string;
  activities_kk?: string;
};
export type Question = {
  id: string;
  lesson_id: string;
  topic: string;
  difficulty: 'Beginner' | 'Intermediate';
  type: 'choice' | 'blank' | 'correction' | 'boolean';
  prompt: string;
  options: string[];
  answer: string;
  explanation: string;
  explanation_de?: string;
  explanation_ru?: string;
  explanation_kk?: string;
};
export type Word = {
  id: string;
  word: string;
  translation: string;
  translation_ru?: string;
  translation_kk?: string;
  definition_kk?: string;
  definition_de?: string;
  definition_ru?: string;
  definition: string;
  example: string;
  theme: string;
  difficulty: string;
};
export type ReadingQuestion = {
  id: string;
  prompt: string;
  options: string[];
  answer: string;
  explanation: string;
  explanation_de?: string;
  explanation_ru?: string;
  explanation_kk?: string;
};
export type Passage = { id: string; title: string; level: string; body: string; questions: ReadingQuestion[] };
export type WritingAssignment = { id: string; title: string; instructions: string; min_words: number; format: string };
export type LessonProgress = { lesson_id: string; status: 'in_progress' | 'completed'; updated_at: string };
export type QuizAnswer = { question_id: string; topic: string; response: string; correct: boolean };
export type Attempt = {
  id: string;
  title: string;
  score: number;
  total: number;
  answers: QuizAnswer[];
  created_at: string;
  kind: 'grammar' | 'reading';
};
export type WordProgress = { vocabulary_id: string; known: boolean; review_at: string; updated_at: string };
export type Draft = {
  id: string;
  assignment_id: string;
  body: string;
  submitted: boolean;
  versions: { body: string; at: string }[];
  updated_at: string;
};
export type Homework = {
  id: string;
  user_id: string;
  lesson_id: string;
  title: string;
  instructions: string;
  due_at: string;
  material_url: string;
  practice_path: string;
};
export type HomeworkSubmission = { id: string; homework_id: string; body: string; submitted_at: string };
export type Feedback = {
  id: string;
  user_id: string;
  submission_id: string;
  kind: 'writing' | 'homework';
  comment: string;
  score: number;
  created_at: string;
};
export type TutoringSession = { id: string; user_id: string; starts_at: string; duration: number; meeting_url: string };
export type Workspace = {
  lessons: Lesson[];
  questions: Question[];
  vocabulary: Word[];
  passages: Passage[];
  writing: WritingAssignment[];
  lessonProgress: LessonProgress[];
  attempts: Attempt[];
  wordProgress: WordProgress[];
  drafts: Draft[];
  homework: Homework[];
  submissions: HomeworkSubmission[];
  feedback: Feedback[];
  sessions: TutoringSession[];
  conciseAttempts: ConciseAttempt[];
};
